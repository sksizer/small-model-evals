// Writes results/summary.md from the ledger's latest view: per machine, a
// quality table (pass count and mean score per suite) and a speed and memory
// table. Each cell is the newest run of that model and suite; a cell whose
// suite has changed since is marked stale. Run on its own after an import:
//
//   bun scripts/summarize.ts
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { RESULTS_DIR, latest, type LedgerRecord } from './ledger.ts'

const GB = 1e9
// Below this, Ollama reused the loaded model (it ignored the new num_ctx) and
// the prompt came from its cache, so there is no cold prompt speed to show.
const RELOAD_MS = 50

const median = (xs: number[]): number => {
  const s = xs.filter(Number.isFinite).sort((a, b) => a - b)
  return s.length === 0 ? Number.NaN : s[Math.floor((s.length - 1) / 2)]!
}
const fmt = (n: number, digits = 1) => (Number.isFinite(n) ? n.toFixed(digits) : '—')
const metric = (r: LedgerRecord, key: string) => r.metrics?.[key] ?? Number.NaN

function perfRows(model: string, records: LedgerRecord[], stale: string): string[] {
  const byCase = new Map<string, LedgerRecord[]>()
  for (const r of records) byCase.set(r.case, [...(byCase.get(r.case) ?? []), r])
  return [...byCase].map(([id, rs]) => {
    // The cold run is the one that loaded the model. Later runs reuse
    // Ollama's prompt cache, so only the cold run's prompt speed is real.
    const cold = rs.reduce((a, b) => (metric(b, 'load_ms') > metric(a, 'load_ms') ? b : a))
    const loaded = median(rs.map((r) => metric(r, 'loaded_bytes')))
    const gpu = median(rs.map((r) => metric(r, 'vram_bytes'))) / loaded
    const prompt = metric(cold, 'load_ms') < RELOAD_MS ? 'cached' : fmt(metric(cold, 'prompt_tps'), 0)
    return `| ${model}${stale} | ${id} | ${fmt(metric(cold, 'load_ms') / 1000)} | ${prompt} | ${fmt(median(rs.map((r) => metric(r, 'decode_tps'))))} | ${fmt(median(rs.map((r) => metric(r, 'embeds_per_s'))), 0)} | ${fmt(loaded / GB, 2)} | ${fmt(gpu * 100, 0)}% |`
  })
}

export function summarize(): string {
  const view = latest()
  const machines = [...new Set(view.map((v) => v.machine))].sort()
  const lines = [
    '# Model evals: latest results',
    '',
    'Generated by `bun scripts/summarize.ts` from `results/ledger/`. Each cell holds, per active case,',
    'the newest result of that model on that machine. **stale** means some results ran against an',
    'older setup; "not run" counts cases the model has never run. Either needs a rerun.',
  ]
  for (const m of machines) {
    const rows = view.filter((v) => v.machine === m)
    const sample = rows[0]!.records[0]!
    const quality = rows.filter((v) => !v.suite.startsWith('perf'))
    const suites = [...new Set(quality.map((v) => v.suite))].sort()
    const models = [...new Set(rows.map((v) => v.model))].sort()
    lines.push(
      '',
      `## ${m}: ${sample.machine.chip}, ${sample.machine.mem_gib} GiB`,
      '',
      '### Quality',
      '',
      'Each cell: cases passed / total · mean score (partial credit) · median latency · run.',
      '',
      `| Model | ${suites.join(' | ')} |`,
      `| --- | ${suites.map(() => '---').join(' | ')} |`,
    )
    for (const model of models) {
      const cells = suites.map((s) => {
        const v = quality.find((q) => q.model === model && q.suite === s)
        if (!v) return 'n/a'
        const rs = v.records
        const passed = rs.filter((r) => r.pass).length
        const mean = rs.reduce((sum, r) => sum + r.score, 0) / rs.length
        const ms = median(rs.map((r) => r.latency_ms))
        const missing = v.missing.length > 0 ? ` · ${v.missing.length} not run` : ''
        return `${passed}/${rs.length} · ${fmt(mean, 2)} · ${fmt(ms / 1000)} s · ${v.run.slice(0, 10)}${v.stale ? ' **stale**' : ''}${missing}`
      })
      if (cells.some((c) => c !== 'n/a')) lines.push(`| ${model} | ${cells.join(' | ')} |`)
    }
    lines.push(
      '',
      '### Speed and memory',
      '',
      'Load and prompt speed come from the cold run (later runs hit the prompt cache); output speed is',
      'the median of the repeats. Loaded is /api/ps `size`; GPU is the share of it in GPU memory.',
      '',
      '| Model | Case | Load s | Prompt tok/s | Output tok/s | Embeds/s | Loaded GB | GPU |',
      '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |',
    )
    for (const v of rows.filter((r) => r.suite.startsWith('perf')).sort((a, b) => a.model.localeCompare(b.model))) {
      lines.push(...perfRows(v.model, v.records, v.stale ? ' (stale)' : ''))
    }
    const errors = rows.flatMap((v) => v.records.filter((r) => r.error).map((r) => `- ${v.model} · ${v.suite} · ${r.case}: ${r.error}`))
    if (errors.length > 0) lines.push('', '### Errors', '', ...errors)
  }
  const out = join(RESULTS_DIR, 'summary.md')
  writeFileSync(out, `${lines.join('\n')}\n`)
  return out
}

if (import.meta.main) console.log(summarize())
